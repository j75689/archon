func snap(files map[string]string) lang.Snapshot {
	m := make(map[string][]byte, len(files))
	for k, v := range files {
		m[k] = []byte(v)
	}
	return lang.Snapshot{Rev: "HEAD", Files: m}
}

func TestMatchRequiresGoMod(t *testing.T) {
	var e Extractor
	if e.Match(snap(nil)) {
		t.Fatal("empty should not match")
	}
	if !e.Match(snap(map[string]string{"go.mod": "module example.com/m\n"})) {
		t.Fatal("go.mod should match")
	}
}

func TestExtractFirstPartyEdgesAndIsolatedNode(t *testing.T) {
	var e Extractor
	g, err := e.Extract(snap(map[string]string{
		"go.mod": "module example.com/m\n",
		"a.go":   "package m\nimport \"example.com/m/b\"\n",
		"b/b.go": "package b\n",
		"c/c.go": "package c\n",
	}))
	if err != nil {
		t.Fatal(err)
	}
	g, err = graph.Compile(g)
	if err != nil {
		t.Fatal(err)
	}
	keys := map[string]bool{}
	for _, n := range g.Nodes {
		keys[n.Key] = true
	}
	if !keys["example.com/m"] || !keys["example.com/m/b"] || !keys["example.com/m/c"] {
		t.Fatalf("nodes: %+v", g.Nodes)
	}
	if len(g.Edges) != 1 || g.Edges[0].From != "example.com/m" || g.Edges[0].To != "example.com/m/b" {
		t.Fatalf("edges: %+v", g.Edges)
	}
}

