func TestRenderMermaidDropsEdgesToGeneratedOrTestOnlyPackages(t *testing.T) {
	var e Extractor
	g, err := e.Extract(snap(map[string]string{
		"go.mod":             "module example.com/m\n",
		"a.go":               "package m\nimport (\n\t\"example.com/m/gen\"\n\t_ \"example.com/m/onlytest\"\n)\n",
		"gen/g.go":           "// Code generated by x; DO NOT EDIT.\npackage gen\n",
		"onlytest/t_test.go": "package onlytest\n",
	}))
	if err != nil {
		t.Fatal(err)
	}
	g, err = graph.Compile(g)
	if err != nil {
		t.Fatal(err)
	}

	got := graph.RenderMermaid(g)
	if strings.Contains(got, "--> \n") {
		t.Fatalf("rendered dangling edge: %q", got)
	}
	if strings.Contains(got, "example.com/m/gen") || strings.Contains(got, "gen\"]") {
		t.Fatalf("generated package must not be rendered: %q", got)
	}
	if strings.Contains(got, "example.com/m/onlytest") || strings.Contains(got, "onlytest\"]") {
		t.Fatalf("test-only package must not be rendered: %q", got)
	}
}

func TestBodyOnlyChangeSameGraph(t *testing.T) {
	var e Extractor
	a := snap(map[string]string{
		"go.mod": "module example.com/m\n",
		"a.go":   "package m\nfunc unexported() { println(1) }\n",
	})
	b := snap(map[string]string{
		"go.mod": "module example.com/m\n",
		"a.go":   "package m\nfunc unexported() { println(2) }\n",
	})
	ga, _ := graph.Compile(mustExtract(t, e, a))
	gb, _ := graph.Compile(mustExtract(t, e, b))
	if !graph.DiffGraphs(ga, gb).Empty() {
		t.Fatal("body-only change must not affect graph")
	}
}

func TestSyntaxError(t *testing.T) {
	var e Extractor
	_, err := e.Extract(snap(map[string]string{
		"go.mod": "module example.com/m\n",
		"a.go":   "package m\nfunc {",
	}))
	if err == nil {
		t.Fatal("expected parse error")
	}
	if !strings.Contains(err.Error(), "a.go") {
		t.Fatalf("path in error: %v", err)
	}
}

func mustExtract(t *testing.T, e Extractor, s lang.Snapshot) graph.Graph {
	t.Helper()
	g, err := e.Extract(s)
	if err != nil {
		t.Fatal(err)
	}
	return g
}
